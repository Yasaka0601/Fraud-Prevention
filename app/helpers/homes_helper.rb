  # カテゴリーで説明文を出し分ける。
  def category_desc(category)
    key = category.name.to_s

    case key
    when /不審電話/
      "偽警察官詐欺、オレオレ詐欺、還付金詐欺など、電話による巧妙な詐欺を見極める稽古。"
    when /詐欺の制度・用語/
      "詐欺に立ち向かうための制度と用語を身につける稽古。"
    when /SNS/
      "なりすまし、投資・副業詐欺、偽サイト誘導など、SNS上の巧妙な詐欺を見抜く稽古。"
    when /メール/
      "宅配・金融機関・公的機関を装ったメールや、偽サイトへ誘導するフィッシングなど、メールを使った巧妙な詐欺を見抜く稽古。"
    when /WEB/
      "偽サイトや偽広告、偽のログイン画面など、Web上の罠に誘導して個人情報やお金を奪う手口を見抜く稽古。"
    when /極/
      "詐欺対策の極（きわみ） 知っていてもほぼ意味がないほど難しいクイズに挑め。"
    end
  end
